export type Armor = 'infantry' | 'light' | 'heavy' | 'building';
export const ARMOR_INDEX: Record<Armor, number> = { infantry: 0, light: 1, heavy: 2, building: 3 };

export type Faction = 'vanguard' | 'ember';
export type ProjectileKind = 'bullet' | 'shell' | 'rocket' | 'flame' | 'laser' | 'artillery' | 'sniper' | 'sonic' | 'bomb' | 'suicide' | 'plasma';

export interface WeaponDef {
  id: string;
  damage: number;
  /** Range in tiles. */
  range: number;
  minRange?: number;
  /** Seconds between shots. */
  cooldown: number;
  burst?: number;
  projectile: ProjectileKind;
  /** Projectile speed in tiles per second (ignored for instant weapons). */
  speed?: number;
  /** Splash radius in tiles. */
  splash?: number;
  /** Damage multiplier vs [infantry, light, heavy, building]. */
  vs: [number, number, number, number];
  sound: string;
  /** What it can shoot at. Defaults to ground only. */
  targets?: 'ground' | 'air' | 'both';
  /** Tower weapons that shut down on low power. */
  needsPower?: boolean;
  /** Beam / plasma colour. */
  color?: string;
}

export type UnitClass = 'infantry' | 'vehicle' | 'aircraft';
export type ProdCategory = 'structure' | 'infantry' | 'vehicle' | 'aircraft';

export interface UnitDef {
  id: string;
  name: string;
  desc: string;
  cls: UnitClass;
  cost: number;
  buildTime: number;
  hp: number;
  armor: Armor;
  /** Tiles per second. */
  speed: number;
  /** Radians per second. */
  turnRate: number;
  sight: number;
  radius: number;
  weapons: WeaponDef[];
  turret?: boolean;
  crusher?: boolean;
  prereq: string[];
  faction?: Faction;
  harvester?: boolean;
  engineer?: boolean;
  /** Plants C4 on structures. */
  commando?: boolean;
  stealth?: boolean;
  selfRepair?: boolean;
  limit?: number;
  /** Flies: ignores terrain, only hit by anti-air weapons. Value is altitude in px. */
  air?: number;
  /** Hovers over water. */
  hover?: boolean;
  /** Legged walker (animated legs). */
  walker?: boolean;
  /** Heals friendly units of this class, hp per second. */
  heal?: { cls: 'infantry' | 'vehicle'; rate: number };
  /** Reveals stealth units within this many tiles. */
  detector?: number;
  /** Shuts down enemy defences within this many tiles. */
  jammer?: number;
  /** Boosts nearby friendly damage. */
  aura?: number;
  /** Deploys into a Construction Yard. */
  deploys?: boolean;
  /** Cannot be crushed by tanks. */
  uncrushable?: boolean;
  hero?: boolean;
  /** Can airlift a friendly vehicle. */
  carrier?: boolean;
}

export interface BuildingDef {
  id: string;
  name: string;
  desc: string;
  w: number;
  h: number;
  cost: number;
  buildTime: number;
  hp: number;
  power: number;
  sight: number;
  prereq: string[];
  faction?: Faction;
  weapon?: WeaponDef;
  produces?: 'infantry' | 'vehicle' | 'aircraft' | 'structure';
  refinery?: boolean;
  superweapon?: 'ion' | 'nuke';
  wall?: boolean;
  radar?: boolean;
  defense?: boolean;
  buildable?: boolean;
}

